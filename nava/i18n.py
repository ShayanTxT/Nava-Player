class Tr:
    """Tiny translator object: tr("key", n=4). English is the default language."""

    def __init__(self, lang="en"):
        self.lang = lang

    def set_lang(self, lang):
        self.lang = lang if lang in STRINGS else "en"

    def __call__(self, key, **kw):
        table = STRINGS.get(self.lang) or STRINGS["en"]
        text = table.get(key) or STRINGS["en"].get(key, key)
        if kw:
            try:
                return text.format(**kw)
            except Exception:
                return text
        return text


TR = Tr()
